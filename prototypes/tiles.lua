local Config = require('config')
local Game = require('game')
local Palette = require('palette')

---------------------------
-- Tainted water is a set of new tile prototypes.
-- One per pollutant for every tile that yields "water" (water, deepwater, the green variants, shallow water, mud).
-- The clone keeps everything about the original except its colour and the fluid it yields.
---------------------------

local function pollute_water_tile(pollutant, sources, effect_reference, map_reference, is_source)
	-- if there is no fluid for this pollutant in the game, there is nothing to pollute
	if not data.raw.fluid[pollutant.fluid] then return end

	for _, source in ipairs(sources) do
		local original = data.raw.tile[source]
		local tile = table.deepcopy(original)
		tile.name = Config.tainted_tile(pollutant.fluid, source)
		tile.localised_name = {"tile-name."..Config.tainted.."-"..Game.fluids.water, {Game.types.fluid.."-name."..pollutant.fluid}}
		tile.fluid = Config.tainted_fluid(pollutant.fluid)
		tile.order = (original.order or "").."-cp["..pollutant.fluid.."]"

		-- never generated by the map generator, only placed by the script
		tile.autoplace = nil

		-- the script places these next to any other water tile
		tile.allowed_neighbors = nil

		-- The tile keeps its original water effect (the shader that draws the surface). Shorelines are masked inside that effect,
		-- so a tile with an effect of its own draws as a hard square at the coast (like deepwater and the green waters, only the colour changes)
		tile.effect_color = Palette.recolor(original.effect_color, pollutant.water_color, effect_reference, 0, 1.5)
		tile.effect_color_secondary = Palette.recolor(original.effect_color, pollutant.water_color, effect_reference / 0.8, 0, 1.5)
		tile.map_color = Palette.recolor(original.map_color, pollutant.map_color, map_reference, 0.6, 1.3)
		tile.map_color.a = 1

		-- Shorelines treat a tainted tile as its clean original, the way the base game merges deepwater and the green waters into "water"
		tile.transition_merges_with_tile = original.transition_merges_with_tile or source

		-- one factoriopedia entry per pollutant instead of one per water depth
		tile.factoriopedia_alternative = (source ~= "water" and is_source["water"]) and
		Config.tainted_tile(pollutant.fluid, "water") or nil

		-- add the polluted water tile to the game
		data:extend({tile})
	end
end

local sources = {}
for name, tile in pairs(data.raw.tile) do if tile.fluid == "water" then sources[#sources + 1] = name end end
table.sort(sources)

local is_source = {}
for _, name in ipairs(sources) do is_source[name] = true end

local effect_reference = data.raw.tile["water"] and data.raw.tile["water"].effect_color and Palette.get_peak(Palette.get_rgba(data.raw.tile["water"].effect_color)) or 0.655
local map_reference = data.raw.tile["water"] and data.raw.tile["water"].map_color and Palette.get_peak(Palette.get_rgba(data.raw.tile["water"].map_color)) or 0.373

for _, pollutant in ipairs(Config.pollutants) do pollute_water_tile(pollutant, sources, effect_reference, map_reference, is_source) end
