local Config = require('config')
local Game = require('game')
local Palette = require('palette')
local Variants = require('variants')

---------------------------
-- Tainted water is a set of new tile prototypes, made for every tile that yields "water" (water, deepwater, the green variants, shallow water, mud).
-- Each clean tile gets every variant in variants.lua: each pollutant at every strength, and blends of two pollutants.
-- The script steps the water through them one tint at a time, so a slick fades in, mixes and fades out gradually.
-- A clone keeps everything about the original except its colour and the fluid it yields.
---------------------------

local steps = Config.taint_steps

-- The colours of `original` fully tainted by `pollutant`.
local function tainted_colors(original, pollutant, effect_reference, map_reference)
	return {
		effect = Palette.recolor(original.effect_color, pollutant.water_color, effect_reference, 0, 1.5),
		secondary = Palette.recolor(original.effect_color, pollutant.water_color, effect_reference / 0.8, 0, 1.5),
		map = Palette.recolor(original.map_color, pollutant.map_color, map_reference, 0.6, 1.3),
	}
end

local function mix_colors(from, to, amount)
	return {effect = Palette.mix(from.effect, to.effect, amount), secondary = Palette.mix(from.secondary, to.secondary, amount), map = Palette.mix(from.map, to.map, amount)}
end

local function fluid_name(index) return {Game.types.fluid.."-name."..Config.pollutants[index].fluid} end

local function pollute_water_tile(source, effect_reference, map_reference, is_source)
	local original = data.raw.tile[source]
	local clean = {
		effect = Palette.get_rgba(original.effect_color),
		secondary = Palette.get_rgba(original.effect_color_secondary or original.effect_color),
		map = Palette.get_rgba(original.map_color),
	}
	local full = {}
	for index, pollutant in ipairs(Config.pollutants) do full[index] = tainted_colors(original, pollutant, effect_reference, map_reference) end

	for _, variant in ipairs(Variants.for_source(source)) do
		local a, b = Config.pollutants[variant.a], variant.b and Config.pollutants[variant.b]
		-- if a pollutant's fluid is not in the game, there is nothing to pollute with it
		if data.raw.fluid[a.fluid] and (not b or data.raw.fluid[b.fluid]) then
			local dominant = Variants.dominant(variant)
			local colors = b and mix_colors(full[variant.a], full[variant.b], variant.k / steps) or mix_colors(clean, full[variant.a], variant.level / steps)

			local tile = table.deepcopy(original)
			tile.name = variant.name
			tile.fluid = Config.tainted_fluid(Config.pollutants[dominant].fluid)
			tile.order = (original.order or "").."-cp["..variant.name.."]"
			if b then
				local other = dominant == variant.a and variant.b or variant.a
				tile.localised_name = {"tile-name."..Config.tainted.."-"..Game.fluids.water.."-blend", fluid_name(dominant), fluid_name(other)}
			else
				tile.localised_name = {"tile-name."..Config.tainted.."-"..Game.fluids.water, fluid_name(variant.a)}
			end

			-- never generated by the map generator, only placed by the script
			tile.autoplace = nil

			-- the script places these next to any other water tile
			tile.allowed_neighbors = nil

			-- The tile keeps its original water effect (the shader that draws the surface): like deepwater and the green waters, only the colour changes.
			tile.effect_color = colors.effect
			tile.effect_color_secondary = colors.secondary
			tile.map_color = colors.map
			tile.map_color.a = 1

			-- Shorelines treat a tainted tile as its clean original, the way the base game merges deepwater and the green waters into "water"
			tile.transition_merges_with_tile = original.transition_merges_with_tile or source

			-- one factoriopedia entry per pollutant: its fully tainted plain water tile stands in for every strength, blend and depth
			local entry = is_source[Game.fluids.water] and Config.tainted_tile(Config.pollutants[dominant].fluid, Game.fluids.water)
			tile.factoriopedia_alternative = entry ~= variant.name and entry or nil

			-- add the polluted water tile to the game
			data:extend({tile})
		end
	end
end

local sources = {}
for name, tile in pairs(data.raw.tile) do if tile.fluid == Game.fluids.water then sources[#sources + 1] = name end end
table.sort(sources)

local is_source = {}
for _, name in ipairs(sources) do is_source[name] = true end

local effect_reference = data.raw.tile["water"] and data.raw.tile["water"].effect_color and Palette.get_peak(Palette.get_rgba(data.raw.tile["water"].effect_color)) or 0.655
local map_reference = data.raw.tile["water"] and data.raw.tile["water"].map_color and Palette.get_peak(Palette.get_rgba(data.raw.tile["water"].map_color)) or 0.373

for _, source in ipairs(sources) do pollute_water_tile(source, effect_reference, map_reference, is_source) end
